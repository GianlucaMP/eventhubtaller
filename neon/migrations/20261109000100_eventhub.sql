begin;

create schema eventhub;
revoke all on schema eventhub from public;

create table eventhub.eventos (
  id integer generated by default as identity primary key,
  titulo text not null,
  descripcion text not null,
  fecha timestamptz not null,
  modalidad text not null,
  capacidad integer not null check (capacidad > 0)
);

create table eventhub.inscripciones (
  id integer generated always as identity primary key,
  evento_id integer not null references eventhub.eventos(id),
  nombre text not null check (char_length(nombre) between 1 and 100),
  email text not null check (char_length(email) between 1 and 254 and email = lower(btrim(email))),
  creada_en timestamptz not null default now(),
  unique (evento_id, email)
);

create view eventhub.catalogo as
select e.id, e.titulo, e.descripcion, e.fecha, e.modalidad, e.capacidad,
       greatest(0, e.capacidad - count(i.id))::integer as "cuposDisponibles"
from eventhub.eventos e
left join eventhub.inscripciones i on i.evento_id = e.id
group by e.id;

create function eventhub.inscribir(p_evento_id integer, p_nombre text, p_email text)
returns text
language plpgsql
set search_path = pg_catalog
as $$
declare
  limite integer;
begin
  -- Con READ COMMITTED, las consultas siguientes ven el alta que liberó el bloqueo.
  select capacidad into limite
  from eventhub.eventos
  where id = p_evento_id
  for update;

  if not found then
    return 'EVENTO_NO_ENCONTRADO';
  end if;

  if exists (
    select 1 from eventhub.inscripciones where evento_id = p_evento_id and email = p_email
  ) then
    return 'INSCRIPCION_DUPLICADA';
  end if;

  if (select count(*) from eventhub.inscripciones where evento_id = p_evento_id) >= limite then
    return 'EVENTO_SIN_CUPO';
  end if;

  insert into eventhub.inscripciones (evento_id, nombre, email)
  values (p_evento_id, p_nombre, p_email);
  return 'CONFIRMADA';
end;
$$;

revoke all on function eventhub.inscribir(integer, text, text) from public;
commit;
